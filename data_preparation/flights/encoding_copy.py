def apply_cyclical_encoding(df, cyclical_vars, max_values):
    """Aplica encoding cíclico de forma eficiente"""
    for var in cyclical_vars:
        if var in df.columns:
            max_val = max_values[var]
            df[f"{var}_sin"] = np.sin(2 * np.pi * df[var] / max_val) + 1
            df[f"{var}_cos"] = np.cos(2 * np.pi * df[var] / max_val) + 1
    df = df.drop(columns=[v for v in cyclical_vars if v in df.columns])
    return df

